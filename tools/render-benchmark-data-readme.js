#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const dataDir = resolveArg("--data-dir");
const outputPath = path.join(dataDir, "README.md");
const currentResultsPath = path.join(dataDir, "bench", "current-results.json");
const historyPath = path.join(dataDir, "bench", "history", "runs.jsonl");

function fail(message) {
  console.error(`render-benchmark-data-readme: ${message}`);
  process.exit(1);
}

function argValue(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) {
    return null;
  }
  const value = process.argv[index + 1];
  if (value == null || value.startsWith("--")) {
    fail(`${name} requires a path`);
  }
  return value;
}

function resolveArg(name) {
  const value = argValue(name);
  if (value == null) {
    fail(`${name} is required`);
  }
  return path.isAbsolute(value) ? value : path.resolve(root, value);
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    fail(`could not read ${filePath}: ${error.message}`);
  }
}

function historyRecordCount() {
  try {
    return fs
      .readFileSync(historyPath, "utf8")
      .split(/\n/)
      .filter((line) => line.trim() !== "").length;
  } catch (error) {
    fail(`could not read ${historyPath}: ${error.message}`);
  }
}

function formatNumber(value, digits = 3) {
  return new Intl.NumberFormat("en-US", {
    maximumFractionDigits: digits,
  }).format(value);
}

function formatSpeed(value) {
  if (value == null) {
    return "n/a";
  }
  if (value >= 100) {
    return `${formatNumber(value, 0)}x`;
  }
  if (value >= 10) {
    return `${formatNumber(value, 2)}x`;
  }
  return `${formatNumber(value, 3)}x`;
}

function iso(timestamp) {
  return new Date(timestamp * 1000).toISOString().replace("T", " ").replace(".000Z", " UTC");
}

function geometricMean(values) {
  const finite = values.filter((value) => Number.isFinite(value) && value > 0);
  if (finite.length === 0) {
    return null;
  }
  return Math.exp(finite.reduce((sum, value) => sum + Math.log(value), 0) / finite.length);
}

function groupBy(values, keyFn) {
  const groups = new Map();
  for (const value of values) {
    const key = keyFn(value);
    const group = groups.get(key);
    if (group) {
      group.push(value);
    } else {
      groups.set(key, [value]);
    }
  }
  return groups;
}

function latestRustiaRows(rows) {
  const rustiaRows = rows.filter((row) => row.engine === "rustia");
  const latestTimestamp = Math.max(...rustiaRows.map((row) => row.timestamp_unix));
  const latestCommit = rustiaRows.find((row) => row.timestamp_unix === latestTimestamp)?.commit;
  return rustiaRows
    .filter((row) => row.commit === latestCommit)
    .sort((left, right) => left.target.localeCompare(right.target) || left.workload.localeCompare(right.workload));
}

function engineSummaries(rows) {
  const fastestByWorkload = new Map();
  for (const group of groupBy(rows, (row) => `${row.target}\0${row.workload}`).values()) {
    const fastest = Math.min(...group.map((row) => row.ns_per_unit_median));
    for (const row of group) {
      fastestByWorkload.set(row, Math.abs(row.ns_per_unit_median - fastest) < 0.000001);
    }
  }
  return [...groupBy(rows, (row) => `${row.target}\0${row.engine}`).entries()]
    .map(([key, group]) => {
      const [target, engine] = key.split("\0");
      return {
        target,
        engine,
        measured: group.length,
        fastest: group.filter((row) => fastestByWorkload.get(row)).length,
        geomean: geometricMean(group.map((row) => row.speed_vs_rustia)),
      };
    })
    .sort((left, right) => {
      const target = left.target.localeCompare(right.target);
      if (target !== 0) {
        return target;
      }
      return (right.geomean ?? -Infinity) - (left.geomean ?? -Infinity);
    });
}

function markdownList(values) {
  return values.map((value) => `\`${value}\``).join(", ");
}

const data = readJson(currentResultsPath);
const rows = data.rows;
const metadata = data.metadata;
const latestRows = latestRustiaRows(rows);
const latestCommit = latestRows[0]?.commit ?? "unknown";
const summaries = engineSummaries(rows);

let output = `# rustia benchmark data

Generated by the [slowchop/rustia](https://github.com/slowchop/rustia) benchmark workflow. Do not edit this file by hand.

- History records: ${historyRecordCount()}
- Current rows: ${metadata.row_count}
- Targets: ${metadata.targets.join(", ")}
- Workloads: ${metadata.workloads.join(", ")}
- Source commits in current snapshot: ${markdownList(metadata.commits)}
- Measurement window: ${iso(metadata.measurement_window_unix.start)} to ${iso(metadata.measurement_window_unix.end)}
- Target scoreboard: [bench/SCOREBOARD.md](bench/SCOREBOARD.md)
- Current HTML report: [bench/current-results.html](bench/current-results.html)
- Current JSON: [bench/current-results.json](bench/current-results.json)

## Latest Rustia Run

Latest Rustia commit: \`${latestCommit}\`

| target | workload | median ns/unit | min ns/unit | n |
| --- | --- | ---: | ---: | ---: |
`;

for (const row of latestRows) {
  output += `| ${row.target} | ${row.workload} | ${formatNumber(row.ns_per_unit_median, 2)} | ${formatNumber(row.ns_per_unit_min, 2)} | ${formatNumber(row.n, 0)} |\n`;
}

output += `
## Native/Host Summary

Speed is geometric mean relative to Rustia for the same target. Higher is faster.

| target | rank | engine | geomean vs rustia | fastest workloads | measured workloads |
| --- | ---: | --- | ---: | ---: | ---: |
`;

let currentTarget = null;
let rank = 0;
for (const summary of summaries) {
  if (summary.target !== currentTarget) {
    currentTarget = summary.target;
    rank = 0;
  }
  rank += 1;
  output += `| ${summary.target} | ${rank} | ${summary.engine} | ${formatSpeed(summary.geomean)} | ${summary.fastest} | ${summary.measured} |\n`;
}

fs.writeFileSync(outputPath, output);
console.log(`wrote ${path.relative(root, outputPath)}`);
