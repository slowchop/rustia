//! Experimental generated Rust for one statically numeric Luau closure.
use crate::{
    source_bundle::{ContentDigest, SourceBundle},
    CompileError,
};
use rustia_lexer::{lex_for_parser, Span};
use rustia_parser::{AssignmentOp, AssignmentTarget, BinaryOp, Chunk, Expr, Parser, Stmt};
use rustia_vm::{number::CANON_NAN_BITS, Program, RetainedValue, Value, Vm};

/// Maximum source size accepted by the experimental compiled-call driver.
pub const MAX_SOURCE_BYTES: usize = 4096;
/// ABI of the generated numeric capture call.
pub const COMPILED_CALL_ABI: &str = "rustia-compiled-call-v1";
// This small grammar needs few tokens. Bound the token stream before entering
// the recursive parser, including ineligible syntax and long flat expressions.
const MAX_TOKENS: usize = 128;

/// Build input for an experimental compiled call.
///
/// Use [`prepare_runtime`] to execute against the interpreter's own capture.
#[derive(Debug)]
pub struct GeneratedCall {
    pub rust: String,
    pub capture_name: String,
    pub initial_capture: f64,
}

/// Identity of an experimental compiled call and the inputs used to build it.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CompiledCallReceipt {
    pub source_digest: ContentDigest,
    pub graph_digest: ContentDigest,
    pub compiler_abi: &'static str,
    pub backend: &'static str,
    pub artifact_digest: ContentDigest,
}

/// Lower an entry from a frozen bundle and identify the exact generated bytes.
///
/// The numeric subset admits no imports. Run its bounded parser first so that
/// unsupported input cannot reach the general graph parser without those limits.
pub fn generate_from_bundle(
    bundle: &SourceBundle,
    entry: &str,
) -> Result<(GeneratedCall, CompiledCallReceipt), CompileError> {
    let (_, call, receipt) = admit_entry(bundle, entry)?;
    Ok((call, receipt))
}

fn admit_entry(
    bundle: &SourceBundle,
    entry: &str,
) -> Result<(Chunk, GeneratedCall, CompiledCallReceipt), CompileError> {
    let bytes = bundle
        .source(entry)
        .ok_or_else(|| CompileError::new(format!("missing compiled module {entry:?}")))?;
    let source = std::str::from_utf8(bytes).map_err(|error| {
        let start = error.valid_up_to();
        let end = error.error_len().map_or(bytes.len(), |len| start + len);
        CompileError::at("compiled module is not UTF-8", Span::new(start, end))
    })?;
    let chunk = parse_bounded(source)?;
    let call = render(lower(&chunk, Span::new(0, source.len()))?);
    let graph = bundle
        .static_module_graph(&[entry])
        .map_err(|error| CompileError {
            message: error.message,
            span: error.span,
        })?;
    let receipt = CompiledCallReceipt {
        source_digest: bundle.digest(),
        graph_digest: graph.digest,
        compiler_abi: COMPILED_CALL_ABI,
        backend: "generated-rust",
        artifact_digest: ContentDigest::of_bytes(call.rust.as_bytes()),
    };
    Ok((chunk, call, receipt))
}

/// VM-independent binding for one numeric artifact and its interpreter program.
pub struct PreparedNumericCall {
    program: Program,
    receipt: CompiledCallReceipt,
    capture: String,
}

/// Prepare the original bytecode from the same frozen entry as the artifact.
/// The receipt belongs to the Rust text before the embedder builds it.
pub fn prepare_runtime(
    bundle: &SourceBundle,
    entry: &str,
) -> Result<PreparedNumericCall, CompileError> {
    let (chunk, generated, receipt) = admit_entry(bundle, entry)?;
    let program = crate::compile(&chunk)?.with_source_name(Some(entry.to_owned()));
    Ok(PreparedNumericCall {
        program,
        receipt,
        capture: generated.capture_name,
    })
}

impl PreparedNumericCall {
    /// Instantiate a new closure with its own interpreter-owned capture cell.
    pub fn instantiate<'artifact>(
        &'artifact self,
        vm: &mut Vm,
    ) -> rustia_vm::Result<NumericCallInstance<'artifact>> {
        let function = vm.run(&self.program)?;
        Ok(NumericCallInstance {
            prepared: self,
            function: vm.retain_value(function)?,
        })
    }
}

/// An instantiated closure rooted in its owning VM.
pub struct NumericCallInstance<'artifact> {
    prepared: &'artifact PreparedNumericCall,
    function: RetainedValue,
}

impl NumericCallInstance<'_> {
    /// Invoke the ordinary interpreter against the same closure.
    pub fn call_interpreted(&self, vm: &mut Vm, parameter: Value) -> rustia_vm::Result<Value> {
        let function = self.function.value(vm)?;
        vm.call_function(&self.prepared.program, function, &[parameter])
    }

    /// At an idle host boundary, invoke trusted generated code against a VM-
    /// owned numeric capture. The embedder must associate this receipt with
    /// the actual executable it built from the original generated bytes.
    ///
    /// Rustia counts the admitted straight-line instructions. A different
    /// receipt, an unsupported profile or operand, or a call that can reach
    /// a fuel, memory, or collection boundary selects the interpreter.
    /// The backend runs before state changes.
    pub fn call(
        &self,
        vm: &mut Vm,
        parameter: Value,
        receipt: &CompiledCallReceipt,
        invoke: impl FnOnce(f64, f64) -> rustia_vm::Result<(f64, f64)>,
    ) -> rustia_vm::Result<Value> {
        if *receipt != self.prepared.receipt {
            return self.call_interpreted(vm, parameter);
        }
        let mut execution = vm.begin_execution();
        match vm.try_run_compiled_numeric_capture(
            &self.function,
            &self.prepared.capture,
            parameter,
            &mut execution,
            invoke,
        )? {
            Some(result) => Ok(result),
            None => self.call_interpreted(vm, parameter),
        }
    }
}

/// Lower a single source module defining one numeric capture and returning a
/// unary closure. The closure may update that capture once before returning.
pub fn generate(source: &str) -> Result<GeneratedCall, CompileError> {
    let chunk = parse_bounded(source)?;
    Ok(render(lower(&chunk, Span::new(0, source.len()))?))
}

fn render(call: NumericCall) -> GeneratedCall {
    GeneratedCall {
        rust: emit_rust(&call),
        capture_name: call.capture_name,
        initial_capture: call.initial_capture,
    }
}

struct NumericCall {
    capture_name: String,
    initial_capture: f64,
    capture_update: Option<NumericExpr>,
    result: NumericExpr,
}

enum NumericExpr {
    Literal(f64),
    Capture,
    Parameter,
    Binary(Arithmetic, Box<NumericExpr>, Box<NumericExpr>),
}

impl NumericExpr {
    fn binary(op: Arithmetic, lhs: Self, rhs: Self) -> Self {
        Self::Binary(op, Box::new(lhs), Box::new(rhs))
    }
}

enum Arithmetic {
    Add,
    Subtract,
    Multiply,
    Divide,
}

fn parse_bounded(source: &str) -> Result<Chunk, CompileError> {
    let module_span = Span::new(0, source.len());
    if source.len() > MAX_SOURCE_BYTES {
        return Err(CompileError::at(
            format!("compiled module exceeds {MAX_SOURCE_BYTES} source bytes"),
            module_span,
        ));
    }
    let tokens = lex_for_parser(source.as_bytes())
        .map_err(|error| CompileError::at(error.message, error.span))?;
    if let Some(token) = tokens.get(MAX_TOKENS) {
        return Err(CompileError::at(
            "compiled module exceeds its token budget",
            token.span,
        ));
    }
    Parser::new(tokens)
        .parse_chunk()
        .map_err(|error| CompileError::at(error.message, error.span))
}

fn lower(chunk: &Chunk, module_span: Span) -> Result<NumericCall, CompileError> {
    let [Stmt::Local {
        bindings,
        init,
        span,
    }, Stmt::Return {
        value:
            Some(Expr::Function {
                attributes,
                params,
                is_vararg: false,
                body,
                span: function_span,
            }),
        extra_values,
        ..
    }] = chunk.statements.as_slice()
    else {
        return Err(CompileError::at(
            "expected one numeric local and a returned closure",
            module_span,
        ));
    };
    let ([binding], [Expr::Number(initial_capture, _)]) = (bindings.as_slice(), init.as_slice())
    else {
        return Err(CompileError::at(
            "expected one literal numeric capture",
            *span,
        ));
    };
    let [parameter] = params.as_ref() else {
        return Err(CompileError::at(
            "expected one numeric parameter",
            *function_span,
        ));
    };
    if !attributes.is_empty() || !extra_values.is_empty() || binding.name == parameter.name {
        return Err(CompileError::at(
            "unsupported compiled closure signature",
            *function_span,
        ));
    }
    let mut lowerer = Lowerer {
        capture: &binding.name,
        parameter: &parameter.name,
        uses_capture: false,
    };
    let (update, result) = match body.as_ref() {
        [Stmt::Return {
            value: Some(result),
            extra_values,
            ..
        }] if extra_values.is_empty() => (None, result),
        [Stmt::Assignment {
            targets,
            op,
            values,
            span,
        }, Stmt::Return {
            value: Some(result),
            extra_values,
            ..
        }] if extra_values.is_empty() => {
            let ([AssignmentTarget::Local { name, .. }], [value]) =
                (targets.as_slice(), values.as_slice())
            else {
                return Err(CompileError::at(
                    "expected one numeric capture assignment",
                    *span,
                ));
            };
            if name != lowerer.capture {
                return Err(CompileError::at(
                    "only the numeric capture can be assigned",
                    *span,
                ));
            }
            lowerer.uses_capture = true;
            let value = lowerer.expression(value)?;
            let arithmetic = match op {
                AssignmentOp::Assign => None,
                AssignmentOp::Add => Some(Arithmetic::Add),
                AssignmentOp::Sub => Some(Arithmetic::Subtract),
                AssignmentOp::Mul => Some(Arithmetic::Multiply),
                AssignmentOp::Div => Some(Arithmetic::Divide),
                _ => return Err(CompileError::at("unsupported numeric assignment", *span)),
            };
            let update = match arithmetic {
                Some(op) => NumericExpr::binary(op, NumericExpr::Capture, value),
                None => value,
            };
            (Some(update), result)
        }
        _ => {
            return Err(CompileError::at(
                "unsupported compiled closure body",
                *function_span,
            ))
        }
    };
    let result = lowerer.expression(result)?;
    if !lowerer.uses_capture {
        return Err(CompileError::at(
            "closure must capture the declared numeric local",
            *function_span,
        ));
    }
    Ok(NumericCall {
        capture_name: binding.name.clone(),
        initial_capture: *initial_capture,
        capture_update: update,
        result,
    })
}

struct Lowerer<'a> {
    capture: &'a str,
    parameter: &'a str,
    uses_capture: bool,
}

impl Lowerer<'_> {
    fn expression(&mut self, expr: &Expr) -> Result<NumericExpr, CompileError> {
        let unsupported = || CompileError::at("unsupported numeric expression", expr.span());
        match expr {
            Expr::Number(value, _) => Ok(NumericExpr::Literal(*value)),
            Expr::Name(name, _) if name == self.capture => {
                self.uses_capture = true;
                Ok(NumericExpr::Capture)
            }
            Expr::Name(name, _) if name == self.parameter => Ok(NumericExpr::Parameter),
            Expr::Paren { expr, .. } => self.expression(expr),
            Expr::Binary { op, lhs, rhs, .. } => {
                let op = match op {
                    BinaryOp::Add => Arithmetic::Add,
                    BinaryOp::Sub => Arithmetic::Subtract,
                    BinaryOp::Mul => Arithmetic::Multiply,
                    BinaryOp::Div => Arithmetic::Divide,
                    _ => return Err(unsupported()),
                };
                Ok(NumericExpr::binary(
                    op,
                    self.expression(lhs)?,
                    self.expression(rhs)?,
                ))
            }
            _ => Err(unsupported()),
        }
    }
}

fn emit_rust(call: &NumericCall) -> String {
    let update = call
        .capture_update
        .as_ref()
        .map(|expr| format!("    let capture = {};\n", emit_rust_expression(expr)))
        .unwrap_or_default();
    let result = emit_rust_expression(&call.result);
    format!(
        "#[inline]\nfn canonical(value: f64) -> f64 {{\n    if value.is_nan() {{ f64::from_bits({CANON_NAN_BITS}) }} else {{ value }}\n}}\n\n\
         pub fn compiled_call(capture: f64, parameter: f64) -> (f64, f64) {{\n\
             let capture = canonical(capture);\n    let parameter = canonical(parameter);\n{update}    (capture, {result})\n}}\n"
    )
}

fn emit_rust_expression(expr: &NumericExpr) -> String {
    match expr {
        NumericExpr::Literal(value) => format!("canonical(f64::from_bits({}))", value.to_bits()),
        NumericExpr::Capture => "capture".to_owned(),
        NumericExpr::Parameter => "parameter".to_owned(),
        NumericExpr::Binary(op, lhs, rhs) => {
            let operator = match op {
                Arithmetic::Add => '+',
                Arithmetic::Subtract => '-',
                Arithmetic::Multiply => '*',
                Arithmetic::Divide => '/',
            };
            format!(
                "canonical({} {operator} {})",
                emit_rust_expression(lhs),
                emit_rust_expression(rhs)
            )
        }
    }
}
